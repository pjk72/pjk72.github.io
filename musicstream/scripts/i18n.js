let currentLang = localStorage.getItem('musicstream_lang') || 'it';

function applyTranslations(lang) {
    if (!translations[lang]) lang = 'it';
    currentLang = lang;
    localStorage.setItem('musicstream_lang', lang);
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (translations[lang][key]) {
            el.placeholder = translations[lang][key];
        }
    });

    // Update search input placeholder separately as well
    const searchInput = document.getElementById('music-search-input');
    if (searchInput) {
        searchInput.placeholder = translations[lang].search_placeholder;
    }

    // Update event search placeholder
    const eventSearchInput = document.getElementById('event-search-input');
    if (eventSearchInput && translations[lang].events_search_placeholder) {
        eventSearchInput.placeholder = translations[lang].events_search_placeholder;
    }

    // Re-render events to update button texts
    if (typeof renderEvents === 'function') {
        renderEvents(eventSearchInput ? eventSearchInput.value : '');
    }

    // Re-fetch events from API with the new locale
    if (typeof fetchLiveEvents === 'function') {
        fetchLiveEvents();
    }

    // Aggiorna l'UI del dropdown
    const langFlag = document.getElementById('current-lang-flag');
    const langText = document.getElementById('current-lang-text');
    if (langFlag && langText) {
        let flagUrl = '';
        let langName = '';
        switch (lang) {
            case 'it': flagUrl = 'https://flagcdn.com/w40/it.png'; langName = 'IT'; break;
            case 'en': flagUrl = 'https://flagcdn.com/w40/gb.png'; langName = 'EN'; break;
            case 'fr': flagUrl = 'https://flagcdn.com/w40/fr.png'; langName = 'FR'; break;
            case 'es': flagUrl = 'https://flagcdn.com/w40/es.png'; langName = 'ES'; break;
            case 'de': flagUrl = 'https://flagcdn.com/w40/de.png'; langName = 'DE'; break;
            default: flagUrl = 'https://flagcdn.com/w40/it.png'; langName = 'IT'; break;
        }
        langFlag.src = flagUrl;
        langText.textContent = langName;
    }

    // Aggiorna il pulsante espansione se esiste
    if (typeof window.refreshExpandBtn === 'function') {
        window.refreshExpandBtn();
    }
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations(currentLang);

    // Logica per il nuovo Custom Dropdown per la lingua
    const langDropdown = document.getElementById('lang-dropdown');
    const langSelected = document.getElementById('lang-dropdown-selected');
    const langOptions = document.querySelectorAll('#lang-dropdown-options li');

    if (langDropdown && langSelected) {
        langSelected.addEventListener('click', (e) => {
            e.stopPropagation();
            langDropdown.classList.toggle('open');
        });

        langOptions.forEach(option => {
            option.addEventListener('click', () => {
                const selectedLang = option.getAttribute('data-lang');
                applyTranslations(selectedLang);
                langDropdown.classList.remove('open');
            });
        });

        // Chiudi il menù se si clicca fuori
        document.addEventListener('click', (e) => {
            if (!langDropdown.contains(e.target)) {
                langDropdown.classList.remove('open');
            }
        });
    }
});
